import fs from "node:fs";
import path from "node:path";
import matter from "gray-matter";
import { remark } from "remark";
import remarkGfm from "remark-gfm";
import remarkHtml from "remark-html";

const WRITING_DIR = path.join(process.cwd(), "docs", "dispatches");

export type WritingType = "essay" | "dispatch";

export interface PostFrontmatter {
  slug: string;
  title: string;
  date: string;
  type: WritingType;
  summary: string;
  draft: boolean;
  framework?: string;
  week?: string;
  quarter?: string;
  window?: string;
}

export interface Post extends PostFrontmatter {
  file: string;
  wordCount: number;
  readingMinutes: number;
  raw: string;
}

export interface PostWithHtml extends Post {
  html: string;
}

function requireField<K extends string>(obj: Record<string, unknown>, key: K, file: string): string {
  const v = obj[key];
  if (typeof v === "string" && v.length > 0) return v;
  if (v instanceof Date) return v.toISOString().slice(0, 10);
  if (typeof v === "number") return String(v);
  throw new Error(`Missing required frontmatter field "${key}" in ${file}`);
}

function parseType(v: unknown, file: string): WritingType {
  if (v === "essay" || v === "dispatch") return v;
  throw new Error(`Invalid "type" in ${file}: expected "essay" | "dispatch", got ${JSON.stringify(v)}`);
}

function wordCount(markdown: string): number {
  return markdown
    .replace(/```[\s\S]*?```/g, " ")
    .replace(/`[^`]*`/g, " ")
    .replace(/!\[[^\]]*\]\([^)]*\)/g, " ")
    .replace(/\[([^\]]+)\]\([^)]*\)/g, "$1")
    .replace(/[#>*_~\-]/g, " ")
    .split(/\s+/)
    .filter(Boolean).length;
}

function readOne(file: string): Post {
  const full = path.join(WRITING_DIR, file);
  const raw = fs.readFileSync(full, "utf8");
  const { data, content } = matter(raw);

  const fm: PostFrontmatter = {
    slug: requireField(data, "slug", file),
    title: requireField(data, "title", file),
    date: requireField(data, "date", file),
    type: parseType(data.type, file),
    summary: requireField(data, "summary", file),
    draft: Boolean(data.draft),
    framework: typeof data.framework === "string" ? data.framework : undefined,
    week: typeof data.week === "string" ? data.week : undefined,
    quarter: typeof data.quarter === "string" ? data.quarter : undefined,
    window: typeof data.window === "string" ? data.window : undefined,
  };

  const wc = wordCount(content);

  return {
    ...fm,
    file,
    wordCount: wc,
    readingMinutes: Math.max(1, Math.round(wc / 220)),
    raw: content,
  };
}

let cache: Post[] | null = null;

function loadAll(): Post[] {
  if (cache) return cache;
  if (!fs.existsSync(WRITING_DIR)) {
    cache = [];
    return cache;
  }
  // Skip *-social.md companions — these are short-form distribution
  // drafts generated by scripts/generate-repurpose.ts and don't carry
  // the essay-shape frontmatter that readOne() requires.
  const files = fs
    .readdirSync(WRITING_DIR)
    .filter((f) => f.endsWith(".md") && !f.endsWith("-social.md"));
  const posts = files
    .map((f) => {
      try {
        return readOne(f);
      } catch (err) {
        if (process.env.NODE_ENV === "production") throw err;
        console.warn(`[writing] skipping ${f}:`, (err as Error).message);
        return null;
      }
    })
    .filter((p): p is Post => p !== null)
    .sort((a, b) => (a.date < b.date ? 1 : -1));
  cache = posts;
  return cache;
}

export function getAllPosts(opts: { includeDrafts?: boolean } = {}): Post[] {
  const { includeDrafts = false } = opts;
  const posts = loadAll();
  return includeDrafts ? posts : posts.filter((p) => !p.draft);
}

export function getPostBySlug(slug: string, opts: { includeDrafts?: boolean } = {}): Post | null {
  const posts = getAllPosts(opts);
  return posts.find((p) => p.slug === slug) ?? null;
}

export function getLatestPosts(n: number, opts: { includeDrafts?: boolean } = {}): Post[] {
  return getAllPosts(opts).slice(0, n);
}

export function getAdjacent(slug: string): { prev: Post | null; next: Post | null } {
  const posts = getAllPosts();
  const i = posts.findIndex((p) => p.slug === slug);
  if (i === -1) return { prev: null, next: null };
  return {
    prev: i < posts.length - 1 ? posts[i + 1] : null,
    next: i > 0 ? posts[i - 1] : null,
  };
}

export async function renderPostHtml(post: Post): Promise<PostWithHtml> {
  const processed = await remark()
    .use(remarkGfm)
    .use(remarkHtml, { sanitize: false })
    .process(post.raw);
  return { ...post, html: String(processed) };
}

export function groupByYear(posts: Post[]): { year: string; posts: Post[] }[] {
  const buckets = new Map<string, Post[]>();
  for (const p of posts) {
    const year = p.date.slice(0, 4);
    if (!buckets.has(year)) buckets.set(year, []);
    buckets.get(year)!.push(p);
  }
  return Array.from(buckets.entries())
    .sort((a, b) => (a[0] < b[0] ? 1 : -1))
    .map(([year, posts]) => ({ year, posts }));
}
